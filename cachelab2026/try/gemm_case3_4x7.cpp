/* case2：32x32x32 -- 4x4 分块；行 0,1 的 A 值跨轮预取（行 2,3 正常读）*/
void gemm_case2(ptr_reg A, ptr_reg B, ptr_reg C, ptr_reg buffer)
{
  for (reg i = 0; i < 8; ++i)
  {
    for (reg j = 0; j < 8; ++j)
    {
      reg acc[4][4];
      for (reg u = 0; u < 4; ++u)
        for (reg v = 0; v < 4; ++v)
          acc[u][v] = 0;

      reg cur0[2], cur1[2]; /* 行 0,1：本轮两个 k 的值（上一轮预取的）*/
      cur0[0] = A[i * 128];
      cur0[1] = A[i * 128 + 1];
      cur1[0] = A[i * 128 + 32];
      cur1[1] = A[i * 128 + 33];

      for (reg kk = 0; kk < 16; ++kk)
      {
        reg av0[2], av1[2]; /* 行 2,3：本轮现读 */
        av0[0] = A[i * 128 + 64 + kk * 2];
        av0[1] = A[i * 128 + 96 + kk * 2];
        av1[0] = A[i * 128 + 64 + kk * 2 + 1];
        av1[1] = A[i * 128 + 96 + kk * 2 + 1];

        reg b0;
        reg n0[2], n1[2]; /* 先趁行还在 cache 里，预取下一轮行 0,1 */
        if (kk + 1 < 16)
        {
          n0[0] = A[i * 128 + (kk + 1) * 2];
          n0[1] = A[i * 128 + (kk + 1) * 2 + 1];
          n1[0] = A[i * 128 + 32 + (kk + 1) * 2];
          n1[1] = A[i * 128 + 32 + (kk + 1) * 2 + 1];
        }

          b0 = B[kk * 64 + j * 4 + 0];
          acc[0][0] += cur0[0] * b0;
          acc[1][0] += cur1[0] * b0;
          acc[2][0] += av0[0] * b0;
          acc[3][0] += av0[1] * b0;
          b0 = B[kk * 64 + 32 + j * 4 + 0];
          acc[0][0] += cur0[1] * b0;
          acc[1][0] += cur1[1] * b0;
          acc[2][0] += av1[0] * b0;
          acc[3][0] += av1[1] * b0;
          b0 = B[kk * 64 + j * 4 + 1];
          acc[0][1] += cur0[0] * b0;
          acc[1][1] += cur1[0] * b0;
          acc[2][1] += av0[0] * b0;
          acc[3][1] += av0[1] * b0;
          b0 = B[kk * 64 + 32 + j * 4 + 1];
          acc[0][1] += cur0[1] * b0;
          acc[1][1] += cur1[1] * b0;
          acc[2][1] += av1[0] * b0;
          acc[3][1] += av1[1] * b0;
          b0 = B[kk * 64 + j * 4 + 2];
          acc[0][2] += cur0[0] * b0;
          acc[1][2] += cur1[0] * b0;
          acc[2][2] += av0[0] * b0;
          acc[3][2] += av0[1] * b0;
          b0 = B[kk * 64 + 32 + j * 4 + 2];
          acc[0][2] += cur0[1] * b0;
          acc[1][2] += cur1[1] * b0;
          acc[2][2] += av1[0] * b0;
          acc[3][2] += av1[1] * b0;
          b0 = B[kk * 64 + j * 4 + 3];
          acc[0][3] += cur0[0] * b0;
          acc[1][3] += cur1[0] * b0;
          acc[2][3] += av0[0] * b0;
          acc[3][3] += av0[1] * b0;
          b0 = B[kk * 64 + 32 + j * 4 + 3];
          acc[0][3] += cur0[1] * b0;
          acc[1][3] += cur1[1] * b0;
          acc[2][3] += av1[0] * b0;
          acc[3][3] += av1[1] * b0;

        cur0[0] = n0[0]; /* 换到下一轮 */
        cur0[1] = n0[1];
        cur1[0] = n1[0];
        cur1[1] = n1[1];
      }

      for (reg u = 0; u < 4; ++u)
        for (reg v = 0; v < 4; ++v)
          C[i * 128 + u * 32 + j * 4 + v] = acc[u][v];
    }
  }
}

